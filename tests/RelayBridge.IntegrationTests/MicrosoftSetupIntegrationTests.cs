        public MicrosoftIdentityException? Error { get; set; }
        public MicrosoftIdentityConfiguration? LastConfiguration { get; private set; }

        public IMicrosoftIdentityClient Create(
            MicrosoftIdentityConfiguration configuration,
            X509Certificate2 certificate)
        {
            LastConfiguration = configuration;
            return new FakeIdentityClient(this, configuration.TenantId);
        }

        private sealed class FakeIdentityClient : IMicrosoftIdentityClient
        {
            private readonly FakeIdentityFactory _owner;
            private readonly Guid _tenantId;

            public FakeIdentityClient(FakeIdentityFactory owner, Guid tenantId)
            {
                _owner = owner;
                _tenantId = tenantId;
            }

            public Task<MicrosoftAccessToken> AcquireTokenAsync(
                string scope,
                CancellationToken cancellationToken)
            {
                cancellationToken.ThrowIfCancellationRequested();
                if (_owner.Error is not null)
                {
                    throw _owner.Error;
                }

                return Task.FromResult(new MicrosoftAccessToken(
                    "fake-m5-token",
                    DateTimeOffset.UtcNow.AddMinutes(30),
                    _tenantId));
            }
        }
    }
