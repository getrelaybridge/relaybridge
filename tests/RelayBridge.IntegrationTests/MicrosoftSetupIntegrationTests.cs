    [Fact]
    public void Generated_object_names_are_stable_per_candidate_and_allow_safe_side_by_side_replacement()
    {
        var generator = new MicrosoftSetupScriptGenerator();
        var generatedAt = DateTimeOffset.Parse("2026-08-22T10:00:00Z");
        var first = ReadyState();
        var second = first with
        {
            Certificate = MicrosoftCertificateReference.Create(new string('B', 40), CertificateStoreTarget.CurrentUser),
            ClientId = Guid.Parse("bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb"),
        };

        using var firstEntra = DecodeScriptPayload(generator.GenerateEntraScript(first, @"C:\public.cer", generatedAt));
        using var stableEntra = DecodeScriptPayload(generator.GenerateEntraScript(first, @"C:\public.cer", generatedAt));
        using var secondEntra = DecodeScriptPayload(generator.GenerateEntraScript(second, @"C:\public.cer", generatedAt));
