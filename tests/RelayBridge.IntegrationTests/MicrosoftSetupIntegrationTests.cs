            firstEntra.RootElement.GetProperty("ApplicationDisplayName").GetString(),
            secondEntra.RootElement.GetProperty("ApplicationDisplayName").GetString());

        using var firstExchange = DecodeScriptPayload(generator.GenerateExchangeScript(first, generatedAt));
        using var secondExchange = DecodeScriptPayload(generator.GenerateExchangeScript(second, generatedAt));
        Assert.NotEqual(
            firstExchange.RootElement.GetProperty("GroupName").GetString(),
            secondExchange.RootElement.GetProperty("GroupName").GetString());
        Assert.NotEqual(
            firstExchange.RootElement.GetProperty("ScopeName").GetString(),
            secondExchange.RootElement.GetProperty("ScopeName").GetString());
        Assert.NotEqual(
            firstExchange.RootElement.GetProperty("AssignmentName").GetString(),
            secondExchange.RootElement.GetProperty("AssignmentName").GetString());
    }

