    private static JsonDocument DecodeScriptPayload(string script)
    {
        const string marker = "FromBase64String('";
        var start = script.IndexOf(marker, StringComparison.Ordinal);
        Assert.True(start >= 0);
        start += marker.Length;
        var end = script.IndexOf("')", start, StringComparison.Ordinal);
        Assert.True(end > start);
        var json = Encoding.UTF8.GetString(Convert.FromBase64String(script[start..end]));
        return JsonDocument.Parse(json);
    }

